/**
 * Regenerate src/lints.generated.ts: the Supabase linter (splinter) SQL exactly as Supabase CLI
 * v2.118.0 runs it for `supabase db advisors`, so the playground's static findings match the CLI's.
 */
import { writeFile } from "node:fs/promises";

const TAG = "v2.118.0";
/** The commit the tag points to; the file was last changed in 2a9063958e33 (2026-09-15). */
const COMMIT = "70b42b8bf64b8cf1fd14c02c013d99dd655626e2";
const PATH = "apps/cli/src/commands/db/advisors/advisors.lints-sql.ts";
const URL_ = `https://raw.githubusercontent.com/supabase/cli/${COMMIT}/${PATH}`;

const source = await (await fetch(URL_)).text();
const literal = /const ADVISORS_LINTS_SQL =\s*("(?:[^"\\]|\\.)*")/s.exec(source)?.[1];
if (!literal) throw new Error(`no ADVISORS_LINTS_SQL in ${URL_}`);
const sql = JSON.parse(literal) as string;
const lints = sql.match(/'[a-z0-9_]+' as name,/g)?.length ?? 0;

await writeFile(
  new URL("../src/lints.generated.ts", import.meta.url),
  `// Generated by scripts/gen-lints.ts. Do not edit by hand.
//
// The Supabase linter (splinter) SQL that Supabase CLI ${TAG} runs for \`supabase db advisors\`,
// from https://github.com/supabase/cli/blob/${COMMIT}/${PATH}
// License: MIT (apps/cli/package.json "license": "MIT"; the published \`supabase\` npm package is
// MIT; text in apps/cli-go/LICENSE, copied to public/licenses/LICENSE-SupabaseCLI.txt). ${lints} lints.

/** The CLI splits on the first ";\\n\\n" into a setup statement and the lints query. */
export const LINTS_SQL: string = ${JSON.stringify(sql)};
`,
);
console.log(`wrote src/lints.generated.ts: ${lints} lints from supabase/cli ${TAG}`);
